"""Generates pdnet's stand-in for the Xbox Live library (XSAPI) from Microsoft.Xbox.Services.winmd.

  py -I generate.py <path to Microsoft.Xbox.Services.winmd>

- gen/      C++/WinRT projection headers + module.g.cpp (regenerated every run; not in git)
- stubs/    one .h/.cpp per XSAPI runtime class.
            Headers are created only when missing. A .cpp is (re)written only while it is still fully generated,
            i.e. it has no "pdnet-hand" marker and no hand-written code. Hand-written files are never touched.
            Unimplemented members log "xsapi-stub: Class::Method returned a default" to pdnet.log and return a
            safe empty value (empty string/list, false/0, a default object of the right type, a finished async op),
            so the game keeps running while we learn what it uses.
"""
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CPPWINRT = r'C:\Program Files (x86)\Windows Kits\10\bin\10.0.22000.0\x64\cppwinrt.exe'
SDK = '10.0.22000.0'
# Linux (build-linux.sh): PDNET_CPPWINRT = path to cppwinrt.exe 2.0.210806.1 (the SDK 10.0.22000 one), run under
# Wine; PDNET_WINRT_REF = folder of Windows .winmd files to resolve references against instead of the SDK.
WINE_CPPWINRT = os.environ.get('PDNET_CPPWINRT')
WINRT_REF = os.environ.get('PDNET_WINRT_REF')


def tool_path(p):
    """A path cppwinrt.exe understands: as is on Windows, Wine's Z: drive on Linux."""
    if not WINE_CPPWINRT:
        return p
    return 'Z:' + os.path.abspath(p).replace('/', '\\')


def cppwinrt(args):
    if WINE_CPPWINRT:
        subprocess.check_call([os.environ.get('WINE', 'wine'), WINE_CPPWINRT] + args)
    else:
        subprocess.check_call([CPPWINRT] + args)
GENERATED_MARK = '// pdnet-generated stub: regenerated by generate.py. When implementing by hand, add a line "// pdnet-hand" so it is kept.'

SCALARS = {'bool', 'int8_t', 'uint8_t', 'int16_t', 'uint16_t', 'int32_t', 'uint32_t', 'int64_t', 'uint64_t',
           'float', 'double', 'char16_t', 'winrt::event_token', 'winrt::guid', 'hstring',
           'Windows::Foundation::PropertyType'}  # Windows enums seen in XSAPI signatures


def split_template(t):
    """'A<B, C<D>>' -> ('A', ['B', 'C<D>'])"""
    if '<' not in t:
        return t, []
    head, inner = t[:t.index('<')], t[t.index('<') + 1:t.rindex('>')]
    args, depth, cur = [], 0, ''
    for ch in inner:
        if ch == '<':
            depth += 1
        elif ch == '>':
            depth -= 1
        if ch == ',' and depth == 0:
            args.append(cur.strip())
            cur = ''
        else:
            cur += ch
    args.append(cur.strip())
    return head, args


def default_value(t, classes, includes):
    """C++ expression for a safe default of projected type t."""
    t = t.strip()
    head, args = split_template(t)
    if t in SCALARS:
        return f'{t}{{}}'
    if head.endswith('com_array'):
        return f'{t}{{}}'
    if head.endswith('Collections::IVectorView'):
        return f'winrt::single_threaded_vector<{args[0]}>().GetView()'
    if head.endswith('Collections::IVector'):
        return f'winrt::single_threaded_vector<{args[0]}>()'
    if head.endswith('Collections::IMapView'):
        return f'winrt::single_threaded_map<{args[0]}, {args[1]}>().GetView()'
    if head.endswith('Collections::IMap'):
        return f'winrt::single_threaded_map<{args[0]}, {args[1]}>()'
    if t in classes:
        impl, header = classes[t]
        includes.add(header)
        return f'winrt::make<{impl}>()'
    if t.startswith('Microsoft::Xbox::Services::') or t in ('Windows::Foundation::TimeSpan', 'Windows::Foundation::DateTime'):
        return f'{t}{{}}'  # XSAPI enums and structs
    return 'nullptr'  # other Windows runtime classes / interfaces


def stub_body(signature, fn, classes, includes):
    m = re.match(r'^(?P<ret>.+?)\s+(?P<cls>\w+)::(?P<name>~?\w+)\s*\(', signature)
    if not m or m.group('ret') in ('static',):
        return f'PDNET_XSAPI_STUB_DEFAULT("{fn}");'  # constructor
    ret = m.group('ret').strip()
    if ret == 'void':
        return f'PDNET_XSAPI_STUB_DEFAULT("{fn}");'
    head, args = split_template(ret)
    if head == 'Windows::Foundation::IAsyncAction':
        return f'PDNET_XSAPI_STUB_DEFAULT("{fn}"); co_return;'
    if head == 'Windows::Foundation::IAsyncOperation':
        return f'PDNET_XSAPI_STUB_DEFAULT("{fn}"); co_return {default_value(args[0], classes, includes)};'
    if head.startswith('Windows::Foundation::IAsync'):
        return f'PDNET_XSAPI_STUB("{fn}");'  # progress variants: not expected; keep the old behaviour
    return f'PDNET_XSAPI_STUB_DEFAULT("{fn}"); return {default_value(ret, classes, includes)};'


def transform_cpp(text, classes):
    text = re.sub(r'\n// Note: Remove this static_assert.*?\nstatic_assert\(false, "[^"]*"\);\n', '\n', text, flags=re.S)
    # newer cppwinrt (2.0.24x+) puts a WARNING comment block and the static_assert at the top instead
    text = re.sub(r'\n// WARNING: This file is automatically generated.*?\nstatic_assert\(false, "[^"]*"\);\n', '\n', text, flags=re.S)
    text = text.replace('#include "pch.h"', '#include "xsapi_pch.h"', 1)
    out, signature, includes = [], '', set()
    for line in text.split('\n'):
        stripped = line.strip()
        if stripped == 'throw hresult_not_implemented();':
            name = re.search(r'(\w+::~?\w+)\s*\(', signature)
            fn = name.group(1) if name else '?'
            line = line.replace('throw hresult_not_implemented();', stub_body(signature, fn, classes, includes))
        elif stripped and stripped not in ('{', '}'):
            signature = stripped
        out.append(line)
    text = '\n'.join(out)
    lines = text.split('\n')
    own = next((i for i, l in enumerate(lines) if l.startswith('#include "') and l != '#include "xsapi_pch.h"'), 1)
    for h in sorted(includes):
        if f'#include "{h}"' not in text:
            lines.insert(own + 1, f'#include "{h}"')
    return GENERATED_MARK + '\n' + '\n'.join(lines)


def transform_h(text):
    return re.sub(r'\n// Note: Remove this static_assert.*?\nstatic_assert\(false, "[^"]*"\);\n', '\n', text, flags=re.S)


def class_table(component_dir):
    """Projected type text -> (implementation type, header) for every generated class."""
    classes = {}
    for name in os.listdir(component_dir):
        if not name.endswith('.h'):
            continue
        parts = name[:-2].split('.')
        ns, cls = parts[:-1], parts[-1]
        projected = '::'.join(['Microsoft', 'Xbox', 'Services'] + ns + [cls])
        impl = 'winrt::' + '::'.join(['Microsoft', 'Xbox', 'Services'] + ns + ['implementation', cls])
        classes[projected] = (impl, name)
    return classes


def is_generated(path):
    """True while every method body is still a single generated stub line."""
    with open(path, encoding='utf-8') as f:
        lines = f.read().split('\n')
    if any(l.strip().startswith('// pdnet-hand') for l in lines):
        return False
    bodies = [i for i, l in enumerate(lines) if l == '    {']
    return bool(bodies) and all(i + 1 < len(lines) and lines[i + 1].strip().startswith('PDNET_XSAPI_STUB') for i in bodies)


def main():
    winmd = sys.argv[1]
    gen = os.path.join(HERE, 'gen')
    stubs = os.path.join(HERE, 'stubs')
    tmp = os.path.join(HERE, 'gen-component')
    shutil.rmtree(gen, ignore_errors=True)
    shutil.rmtree(tmp, ignore_errors=True)
    cppwinrt(['-in', tool_path(winmd), '-ref', tool_path(WINRT_REF) if WINRT_REF else SDK,
              '-component', tool_path(tmp), '-out', tool_path(gen)])
    classes = class_table(tmp)

    os.makedirs(stubs, exist_ok=True)
    created = rewritten = kept = 0
    for name in sorted(os.listdir(tmp)):
        with open(os.path.join(tmp, name), encoding='utf-8') as f:
            text = f.read()
        dst = os.path.join(stubs, name)
        exists = os.path.exists(dst)
        if name.endswith('.h'):
            if exists:
                kept += 1
                continue
            new = transform_h(text)
        else:
            if exists and not is_generated(dst):
                kept += 1
                continue
            new = transform_cpp(text, classes)
        with open(dst, 'w', encoding='utf-8', newline='\n') as f:
            f.write(new)
        if exists:
            rewritten += 1
        else:
            created += 1
    shutil.rmtree(tmp, ignore_errors=True)

    module = os.path.join(gen, 'module.g.cpp')
    with open(module, encoding='utf-8') as f:
        text = f.read().replace('#include "pch.h"', '#include "xsapi_pch.h"', 1)
    with open(module, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'projection + module.g.cpp regenerated in {gen}')
    print(f'stubs: {created} created, {rewritten} regenerated, {kept} hand-written or headers kept as-is')


main()
